test('a pointer can cross a zero-padding host gutter to the block type and handle', async ({ page }) => {
  await openDocument(page, 'First\n\nSecond')
  await page.addStyleTag({ content: '.document-scroll { padding: 0; margin: 40px 80px }' })
  const block = page.locator('.editor-content > p').first()
  await block.hover()
  const box = (await block.boundingBox())!
  const type = page.locator('.drag-handle').getByRole('button', { name: '当前 Block 菜单', exact: true })
  const handle = page.getByRole('button', { name: 'Block 菜单', exact: true })
  await expect(handle).toBeVisible()
  const target = (await handle.boundingBox())!
  await page.mouse.move(box.x + 2, box.y + 12)
  await page.mouse.move(target.x + target.width / 2, target.y + target.height / 2, { steps: 16 })
  await expect(handle).toBeVisible()
  expect(
    await handle.evaluate(element => {
      const box = element.getBoundingClientRect()
      return element.contains(document.elementFromPoint(box.x + box.width / 2, box.y + box.height / 2))
    })
  ).toBe(true)
  expect((await type.boundingBox())!.x).toBeLessThan(target.x)
  expect(target.x + target.width).toBeLessThanOrEqual(box.x)
  await handle.click()
  await page.getByRole('menuitem', { name: '创建副本', exact: true }).click()
  await expect(page.locator('.editor-content > p')).toHaveText(['First', 'First', 'Second'])
})

