defmodule Mix.Tasks.Ankole.Toolkits do
  @moduledoc "Generates or checks Skill MCP declarations, single-tool references, and Applet toolkit types."
  use Mix.Task
  @shortdoc "Checks generated connector toolkit contracts (use --write to update)"
  @requirements ["app.config"]

  def run(args) when args in [[], ["--write"]] do
    root = Path.expand("../..", File.cwd!())

    declarations =
      Application.fetch_env!(:ankole, :control_plane_plugin_modules)
      |> Enum.flat_map(fn module ->
        Code.ensure_loaded!(module)

        if function_exported?(module, :adapter_declarations, 0),
          do: module.adapter_declarations(),
          else: []
      end)
      |> Enum.filter(&(&1.contract_id == "connectors.connector"))

    tools =
      declarations
      |> Enum.flat_map(fn declaration ->
        Code.ensure_loaded!(declaration.module)
        declaration.module.tools()
      end)
      |> Enum.sort_by(&{&1.toolkit, &1.name})

    if tools == [], do: Mix.raise("No connector tool contracts were compiled")

    if length(tools) != length(Enum.uniq_by(tools, &{&1.toolkit, &1.name})),
      do: Mix.raise("Duplicate toolkit tool name")

    contract_paths =
      for {toolkit, tools} <- Enum.group_by(tools, & &1.toolkit) do
        plugin =
          Enum.find(
            declarations,
            &Enum.any?(&1.module.tools(), fn tool -> tool.toolkit == toolkit end)
          ).id

        skill = String.replace(toolkit, "_", "-")
        path = Path.join(root, "app/library/agent-plugins/#{plugin}/skills/#{skill}")

        yaml =
          ~s(dependencies:\n  tools:\n    - type: "mcp"\n      value: #{inspect(toolkit)}\n      transport: "connector"\n      toolkit: #{inspect(toolkit)}\n      enabled_tools:\n) <>
            Enum.map_join(tools, "", &"        - #{inspect(&1.name)}\n")

        sync(Path.join(path, "agents/openai.yaml"), yaml, args)

        index =
          "# #{toolkit} operations\n\nChoose the operation below, then read only its linked contract.\n\n" <>
            Enum.map_join(tools, "\n", fn tool ->
              "- [#{tool.name}](#{tool.name}.json): #{tool.description}"
            end) <> "\n"

        sync(Path.join(path, "references/index.md"), index, args)

        # The check compares JSON contracts by value, so only `--write` formats
        # them, in one oxfmt run over every contract below.
        for tool <- tools do
          contract_path = Path.join(path, "references/#{tool.name}.json")
          contract = Ankole.Connectors.ToolSpec.public(tool)
          sync(contract_path, Torque.encode!(contract, pretty: true) <> "\n", args)
          contract_path
        end
      end

    if args == ["--write"], do: format_in_place(List.flatten(contract_paths), root)

    sync_toolkit_declarations(root, tools, args)
    Mix.shell().info("#{length(tools)} connector tool contracts are current")
  end

  def run(_), do: Mix.raise("usage: mix ankole.toolkits [--write]")

  @doc false
  def render_toolkit_declarations(tools) when is_list(tools) do
    toolkits_by_name =
      tools
      |> Enum.sort_by(&{&1.toolkit, &1.name})
      |> Enum.group_by(& &1.toolkit)
      |> Enum.sort()

    per_toolkit =
      Map.new(toolkits_by_name, fn {toolkit, toolkit_tools} ->
        content =
          "// Generated by mix ankole.toolkits --write from connector ToolSpec contracts.\n" <>
            "/** This entry only declares types. Import it with `import type`. */\n" <>
            toolkit_type_map("Inputs", toolkit_tools, :input_schema) <>
            "\n" <>
            toolkit_type_map("Outputs", toolkit_tools, :output_schema) <>
            "\nexport type Tool = keyof Inputs;\n"

        {"#{toolkit}.d.ts", content}
      end)

    Map.put(per_toolkit, "index.d.ts", render_barrel_declaration(toolkits_by_name))
  end

  defp sync_toolkit_declarations(root, tools, args) do
    toolkits_dir = Path.join(root, "libs/applet-sdk/src/toolkits")
    legacy_path = Path.join(root, "libs/applet-sdk/src/toolkits.ts")
    rendered = render_toolkit_declarations(tools)
    formatted = format_declarations(rendered, root)

    for {filename, content} <- Enum.sort(formatted) do
      sync(Path.join(toolkits_dir, filename), content, args)
    end

    expected = MapSet.new(Map.keys(rendered))
    reconcile_extra_declarations(toolkits_dir, legacy_path, expected, args)
  end

  defp reconcile_extra_declarations(toolkits_dir, legacy_path, expected, ["--write"]) do
    File.rm_rf!(legacy_path)

    if File.dir?(toolkits_dir) do
      for entry <- File.ls!(toolkits_dir), not MapSet.member?(expected, entry) do
        File.rm_rf!(Path.join(toolkits_dir, entry))
      end
    end
  end

  defp reconcile_extra_declarations(toolkits_dir, legacy_path, expected, []) do
    if File.exists?(legacy_path) do
      Mix.raise("#{legacy_path} is obsolete; run mix ankole.toolkits --write")
    end

    extras =
      if File.dir?(toolkits_dir) do
        toolkits_dir
        |> File.ls!()
        |> Enum.reject(&MapSet.member?(expected, &1))
        |> Enum.sort()
      else
        []
      end

    if extras != [] do
      Mix.raise(
        "Unexpected files in #{toolkits_dir} (#{Enum.join(extras, ", ")}); run mix ankole.toolkits --write"
      )
    end
  end

  defp sync(path, content, ["--write"]) do
    File.mkdir_p!(Path.dirname(path))
    File.write!(path, content)
  end

  defp sync(path, content, []) do
    current? =
      case File.read(path) do
        {:ok, saved} ->
          if(Path.extname(path) == ".json",
            do: Torque.decode!(saved) == Torque.decode!(content),
            else: saved == content
          )

        _ ->
          false
      end

    unless current?, do: Mix.raise("#{path} is stale; run mix ankole.toolkits --write")
  end

  defp format_declarations(declarations, root) do
    tmp_dir =
      Path.join(
        System.tmp_dir!(),
        "ankole-toolkit-contracts-#{System.unique_integer([:positive])}"
      )

    File.mkdir_p!(tmp_dir)

    try do
      paths =
        for {filename, content} <- Enum.sort(declarations) do
          path = Path.join(tmp_dir, filename)
          File.write!(path, content)
          {filename, path}
        end

      format_in_place(Enum.map(paths, &elem(&1, 1)), root)
      Map.new(paths, fn {filename, path} -> {filename, File.read!(path)} end)
    after
      File.rm_rf(tmp_dir)
    end
  end

  defp format_in_place(paths, root) do
    case System.cmd(
           Path.join(root, "node_modules/.bin/oxfmt"),
           ["--config", Path.join(root, ".oxfmtrc.json") | paths],
           stderr_to_stdout: true
         ) do
      {_, 0} -> :ok
      {message, _} -> Mix.raise(message)
    end
  end

  defp render_barrel_declaration(toolkits_by_name) do
    header =
      "// Generated by mix ankole.toolkits --write from connector ToolSpec contracts.\n" <>
        "/** This entry only declares types. Import it with `import type`. */\n"

    imports =
      Enum.map_join(toolkits_by_name, "", fn {toolkit, _} ->
        prefix = toolkit_alias_prefix(toolkit)

        "import type { Inputs as #{prefix}_Inputs, Outputs as #{prefix}_Outputs } from #{inspect("./" <> toolkit)};\n"
      end)

    inputs =
      "export interface ToolkitInputs {\n" <>
        Enum.map_join(toolkits_by_name, "", fn {toolkit, _} ->
          "  #{inspect(toolkit)}: #{toolkit_alias_prefix(toolkit)}_Inputs;\n"
        end) <> "}\n"

    outputs =
      "export interface ToolkitOutputs {\n" <>
        Enum.map_join(toolkits_by_name, "", fn {toolkit, _} ->
          "  #{inspect(toolkit)}: #{toolkit_alias_prefix(toolkit)}_Outputs;\n"
        end) <> "}\n"

    header <>
      imports <>
      "\n" <>
      inputs <>
      "\n" <>
      outputs <>
      "\nexport type Toolkit = keyof ToolkitInputs;\nexport type ToolkitTool<T extends Toolkit> = keyof ToolkitInputs[T];\n"
  end

  defp toolkit_alias_prefix(toolkit) do
    "Toolkit_" <> String.replace(toolkit, ~r/[^A-Za-z0-9_]/, "_")
  end

  defp toolkit_type_map(name, toolkit_tools, schema_key) do
    definitions =
      Enum.map_join(toolkit_tools, "", fn tool ->
        schema = tool_schema(tool, schema_key)
        references = references(tool, schema_key, schema)

        definitions = schema_definitions(schema)
        used = used_references(schema, Map.new(definitions), MapSet.new())

        definitions
        |> Enum.filter(fn {ref, _} -> MapSet.member?(used, ref) end)
        |> Enum.map_join("", fn {ref, definition} ->
          "type #{references[ref]} = #{ts(definition, references)};\n"
        end)
      end)

    definitions <>
      "export interface #{name} {\n" <>
      Enum.map_join(toolkit_tools, "", fn tool ->
        schema = tool_schema(tool, schema_key)
        "  #{inspect(tool.name)}: #{ts(schema, references(tool, schema_key, schema))};\n"
      end) <> "}\n"
  end

  defp tool_schema(tool, :output_schema),
    do: Ankole.Connectors.ToolSpec.public_output_schema(tool)

  defp tool_schema(tool, key), do: Map.fetch!(tool, key)

  defp schema_definitions(schema) do
    for owner <- ["$defs", "definitions"],
        {name, definition} <- Enum.sort(schema[owner] || %{}) do
      escaped = name |> String.replace("~", "~0") |> String.replace("/", "~1")
      {"#/#{owner}/#{escaped}", definition}
    end
  end

  defp used_references(schema, definitions, used) when is_map(schema) do
    used =
      case schema["$ref"] do
        nil ->
          used

        ref ->
          if MapSet.member?(used, ref),
            do: used,
            else:
              used_references(Map.fetch!(definitions, ref), definitions, MapSet.put(used, ref))
      end

    schema
    |> Map.drop(["$defs", "definitions", "examples", "default", "enum", "const"])
    |> Enum.reduce(used, fn
      {key, fields}, used when key in ["properties", "patternProperties"] ->
        fields |> Map.values() |> Enum.reduce(used, &used_references(&1, definitions, &2))

      {_, value}, used ->
        used_references(value, definitions, used)
    end)
  end

  defp used_references(values, definitions, used) when is_list(values),
    do: Enum.reduce(values, used, &used_references(&1, definitions, &2))

  defp used_references(_value, _definitions, used), do: used

  defp references(tool, schema_key, schema) do
    schema
    |> schema_definitions()
    |> Enum.with_index(1)
    |> Map.new(fn {{ref, _}, index} ->
      {ref, "Toolkit_#{tool.toolkit}_#{tool.name}_#{schema_key}_#{index}"}
    end)
  end

  defp compound(schema, key, branches, operator, references) do
    base = Map.delete(schema, key)

    Enum.map_join(branches, operator, fn branch ->
      merged = Map.merge(base, branch)

      merged =
        if base["properties"],
          do:
            Map.put(
              merged,
              "properties",
              Map.merge(base["properties"], branch["properties"] || %{})
            ),
          else: merged

      merged =
        if base["required"],
          do:
            Map.put(merged, "required", Enum.uniq(base["required"] ++ (branch["required"] || []))),
          else: merged

      ts(merged, references)
    end)
  end

  defp ts(%{"$ref" => ref}, references), do: Map.fetch!(references, ref)
  defp ts(%{"const" => value}, _references), do: Ankole.JSON.encode!(value)

  defp ts(%{"enum" => values}, _references),
    do: Enum.map_join(values, " | ", &Ankole.JSON.encode!/1)

  defp ts(%{"oneOf" => schemas} = schema, references),
    do: compound(schema, "oneOf", schemas, " | ", references)

  defp ts(%{"anyOf" => schemas} = schema, references),
    do: compound(schema, "anyOf", schemas, " | ", references)

  defp ts(%{"allOf" => schemas} = schema, references),
    do: compound(schema, "allOf", schemas, " & ", references)

  defp ts(%{"type" => types} = schema, references) when is_list(types),
    do: Enum.map_join(types, " | ", &ts(Map.put(schema, "type", &1), references))

  defp ts(%{"type" => "array", "items" => items}, references),
    do: "Array<#{ts(items, references)}>"

  defp ts(%{"type" => "object"} = schema, references) do
    properties = schema |> Map.get("properties", %{}) |> Enum.sort()

    fields =
      Enum.map_join(properties, " ", fn {name, value} ->
        inspect(name) <>
          if(name in (schema["required"] || []), do: ": ", else: "?: ") <>
          ts(value, references) <> ";"
      end)

    additional =
      case schema["additionalProperties"] do
        false ->
          ""

        value when is_map(value) and properties == [] ->
          " [key: string]: #{ts(value, references)};"

        _ ->
          " [key: string]: unknown;"
      end

    "{ " <> fields <> additional <> " }"
  end

  defp ts(%{"type" => type}, _references) when type in ["integer", "number"], do: "number"
  defp ts(%{"type" => type}, _references) when type in ["boolean", "string", "null"], do: type
  defp ts(false, _references), do: "never"
  defp ts(_, _references), do: "unknown"
end
