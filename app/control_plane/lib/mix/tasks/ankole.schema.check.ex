defmodule Mix.Tasks.Ankole.Schema.Check do
  use Mix.Task

  @shortdoc "Checks the committed PostgreSQL schema"
  @requirements ["app.config"]
  @diff_version "v1.0.9"

  @impl Mix.Task
  def run(args) when args in [[], ["--write"]] do
    edition = Application.fetch_env!(:ankole, :edition)
    url = URI.parse(System.fetch_env!("DATABASE_URL"))
    {path, sql} = snapshot(edition, url)

    case args do
      ["--write"] -> with_temporary_file(path, sql, &File.rename!(&1, path))
      [] -> check_snapshot!(path, sql)
    end

    Mix.shell().info("#{Path.relative_to_cwd(path)} is current")
  end

  defp snapshot(:foss, url) do
    path = Path.expand("priv/repo/structure.sql")

    with_database(:foss, url, fn database ->
      {path, "-- Generated by mix ankole.schema.check --write.\n" <> dump(database)}
    end)
  end

  defp snapshot(:saas, url) do
    unless System.find_executable("pg-schema-diff") do
      Mix.raise(
        "Install pg-schema-diff with go install github.com/stripe/pg-schema-diff/cmd/pg-schema-diff@#{@diff_version}"
      )
    end

    repo_dir = Application.fetch_env!(:ankole, :internal_migrations_path) |> Path.dirname()
    path = Path.join(repo_dir, "saas_schema_diff.sql")

    with_database(:foss, url, fn foss ->
      with_database(:saas, url, fn saas ->
        prepare_snapshot!(saas, repo_dir)

        json =
          postgres!(
            "pg-schema-diff",
            [
              "plan",
              "--from-dsn",
              dsn(foss),
              "--to-dsn",
              dsn(saas),
              "--data-pack-new-tables=false",
              "--no-concurrent-index-ops",
              "--disable-plan-validation",
              "--output-format",
              "json"
            ],
            saas
          )

        statements =
          case Ankole.JSON.decode!(json) do
            %{"statements" => nil} -> []
            %{"statements" => statements} -> statements
          end

        sql = Enum.map_join(statements, "\n\n", fn %{"ddl" => ddl} -> ddl <> ";" end)

        validate_delta!(foss, saas, sql)

        {path,
         "-- Generated by mix ankole.schema.check --write. Base: Ankole FOSS.\n" <> sql <> "\n"}
      end)
    end)
  end

  defp with_database(edition, url, callback) do
    partition = "_schema_" <> Base.encode16(:crypto.strong_rand_bytes(8), case: :lower)
    database = %{url | path: "/ankole_test" <> partition}

    env = [
      {"MIX_ENV", "test"},
      {"MIX_TEST_PARTITION", partition},
      {"ANKOLE_EDITION", Atom.to_string(edition)},
      {"BASE_DB_URLS", ""}
    ]

    command!("mix", ["ecto.create", "--quiet"], env)

    try do
      command!("mix", ["ecto.migrate", "--quiet"], env)
      callback.(database)
    after
      command!("mix", ["ecto.drop", "--quiet"], env)
    end
  end

  defp dump(database) do
    postgres!(
      "pg_dump",
      [
        "--no-password",
        "--schema-only",
        "--no-owner",
        "--no-privileges",
        "--dbname",
        dsn(database)
      ],
      database
    )
    |> String.replace(~r/^(?:\\(?:un)?restrict \S+|-- Dumped (?:from|by) .*?)\n/m, "")
    |> String.trim()
    |> Kernel.<>("\n")
  end

  defp validate_delta!(foss, saas, sql) do
    # pg-schema-diff rebuilds schemas without ordering dependent extensions.
    with_temporary_file(Path.join(System.tmp_dir!(), "ankole-schema-delta"), sql, fn path ->
      apply_sql!(foss, path)
    end)

    compare!(dump(foss), dump(saas), "The schema delta did not reproduce the SaaS schema.")
  end

  defp prepare_snapshot!(database, repo_dir) do
    script = Path.join(repo_dir, "schema_snapshot_prepare.sql")

    if File.exists?(script), do: apply_sql!(database, script)
  end

  defp apply_sql!(database, path) do
    postgres!(
      "psql",
      [
        "-X",
        "--no-password",
        "--set",
        "ON_ERROR_STOP=1",
        "--dbname",
        dsn(database),
        "--file",
        path
      ],
      database
    )
  end

  defp dsn(uri), do: URI.to_string(%{uri | scheme: "postgresql", userinfo: nil})

  defp postgres!(command, args, uri) do
    [username | password] = String.split(uri.userinfo || "", ":", parts: 2)

    env = [
      {"PGUSER", if(username == "", do: System.get_env("PGUSER"), else: URI.decode(username))},
      {"PGPASSWORD", Enum.find_value(password, System.get_env("PGPASSWORD"), &URI.decode/1)}
    ]

    command!(command, args, env)
  end

  defp command!(command, args, env) do
    case System.cmd(command, args, env: env) do
      {output, 0} -> output
      {output, status} -> Mix.raise("#{command} failed with exit status #{status}\n#{output}")
    end
  end

  defp check_snapshot!(path, sql) do
    case File.read(path) do
      {:ok, committed} ->
        compare!(
          committed,
          sql,
          "#{Path.relative_to_cwd(path)} is out of date. Run mix ankole.schema.check --write."
        )

      {:error, :enoent} ->
        Mix.raise("Missing #{Path.relative_to_cwd(path)}. Run mix ankole.schema.check --write.")
    end
  end

  defp compare!(sql, sql, _message), do: :ok

  defp compare!(actual, expected, message) do
    root = System.tmp_dir!()

    with_temporary_file(Path.join(root, "ankole-schema-actual"), actual, fn left ->
      with_temporary_file(Path.join(root, "ankole-schema-expected"), expected, fn right ->
        {diff, 1} = System.cmd("diff", ["-u", "-L", "actual", "-L", "expected", left, right])
        Mix.raise("#{message}\n#{diff}")
      end)
    end)
  end

  defp with_temporary_file(path, sql, callback) do
    temporary = path <> "." <> Base.encode16(:crypto.strong_rand_bytes(8), case: :lower)

    try do
      File.write!(temporary, sql, [:exclusive])
      callback.(temporary)
    after
      File.rm(temporary)
    end
  end
end
