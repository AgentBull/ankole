  test "changing a table resolves fields within the new table and changes the runtime digest",
       ctx do
    {:ok, base} = Pages.create(ctx.actor, %{type: "base", private_owner_uid: ctx.uid})
    {:ok, first} = Bases.create_table(ctx.actor, base.id, %{name: "Original"})
    {:ok, second} = Bases.create_table(ctx.actor, base.id, %{name: "Replacement"})
    {:ok, amount_a} = Bases.create_field(ctx.actor, first.id, %{name: "amount", type: "number"})
    {:ok, amount_b} = Bases.create_field(ctx.actor, second.id, %{name: "amount", type: "number"})

    {:ok, wrong_type} =
      Bases.create_field(ctx.actor, second.id, %{name: "status", type: "number"})

    {:ok, status_a} = Bases.create_field(ctx.actor, first.id, %{name: "status", type: "select"})

    manifest = %{
      "tables" => %{
        "orders" => %{
          "tableId" => first.id,
          "required" => true,
          "fields" => %{
            "amount" => %{"fieldId" => amount_a.id, "type" => "number"},
            "status" => %{"fieldId" => status_a.id, "type" => "select"}
          }
        }
      }
    }

    publish(ctx, 0, "one", [{"applet.bindings.json", Torque.encode!(manifest)}])
    assert {:ok, original} = Bindings.list(ctx.actor, ctx.page.id)
    assert original.bindings["orders"].fields["amount"] == amount_a.id

    assert {:ok, replacement} =
             Bindings.put(ctx.actor, ctx.page.id, "orders", %{table_id: second.id})

    assert replacement.bindings["orders"].tableId == second.id
    assert replacement.bindings["orders"].fields["amount"] == amount_b.id
    assert replacement.bindings["orders"].fields["status"] == nil
    assert replacement.bindings["orders"].missing == ["status"]
    refute replacement.bindings_digest == original.bindings_digest

    assert {:ok, explicit} =
             Bindings.put(ctx.actor, ctx.page.id, "orders", %{
               table_id: second.id,
               field_overrides: %{"amount" => amount_a.id, "status" => wrong_type.id}
             })

    assert explicit.bindings["orders"].missing == ["amount", "status"]
    assert {:ok, reset} = Bindings.delete(ctx.actor, ctx.page.id, "orders")
    assert reset.bindings_digest == original.bindings_digest
  end

  test "replaced draft IDs never load or promote a different draft; rollback preserves runtime assets",
       ctx do
    assert {:ok, %{revision: 1}} = publish(ctx, 0, "live")

    assert {:ok, %{draft: first}} =
             publish(ctx, 1, "first draft", [], draft: true, summary: "First")

    assert {:ok, %{draft: second}} =
             publish(ctx, 1, "second draft", [], draft: true, summary: "Second")

    refute first.id == second.id

    assert {:error, {:applet_revision_changed, _}} =
             Files.resolve_applet_frame_object(
               ctx.actor,
               ctx.page.id,
               "draft:" <> first.id,
               "index.html"
             )

    assert {:error, :draft_changed} = Revisions.promote(ctx.actor, ctx.page.id, first.id, 1)
    assert {:error, :draft_changed} = Revisions.discard(ctx.actor, ctx.page.id, first.id, 1)

    assert {:ok, live} =
             Files.resolve_applet_frame_object(ctx.actor, ctx.page.id, 1, "index.html")

    assert {:ok, "live"} = Drive.read_object(live.object_id)

    assert {:ok, draft} =
             Files.resolve_applet_frame_object(
               ctx.actor,
               ctx.page.id,
               "draft:" <> second.id,
               "index.html"
             )

    assert {:ok, "second draft"} = Drive.read_object(draft.object_id)
    assert {:ok, %{revision: 2}} = Revisions.promote(ctx.actor, ctx.page.id, second.id, 1)
    assert Revisions.draft(ctx.page.id) == nil
    {:ok, artifact} = Drive.store("runtime generated bytes")

    assert {:ok, _} =
             Repo.transact_top_level(fn ->
               Files.commit_files_in_tx(ctx.page.id, [
                 %{path: "assets/report.txt", object: artifact, content_type: "text/plain"}
               ])
             end)

    assert {:ok, %{revision: 3}} = Revisions.rollback(ctx.actor, ctx.page.id, 1, 2)

    assert {:ok, restored} =
             Files.resolve_applet_frame_object(ctx.actor, ctx.page.id, 3, "index.html")

    assert {:ok, "live"} = Drive.read_object(restored.object_id)
    assert {:ok, asset} = Files.fetch_file(ctx.page.id, "assets/report.txt")
    assert {:ok, "runtime generated bytes"} = Drive.read_object(asset.object_id)
    assert Revisions.published(ctx.page.id, 3).restored_from_revision == 1
    assert {"pod_applet_revision_files", "object_id"} in Drive.object_references()
  end

