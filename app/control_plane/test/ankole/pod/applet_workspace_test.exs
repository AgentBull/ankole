  test "draft promotion and baseline rollback restore real routes and Action policy while preserving page configuration",
       ctx do
    {:ok, base} = Pages.create(ctx.actor, %{type: "base", private_owner_uid: ctx.uid})
    {:ok, first_table} = Bases.create_table(ctx.actor, base.id, %{name: "Default"})
    {:ok, chosen_table} = Bases.create_table(ctx.actor, base.id, %{name: "Chosen"})

    binding_manifest =
      Torque.encode!(%{
        "tables" => %{"orders" => %{"tableId" => first_table.id, "fields" => %{}}}
      })

    source = """
    export default {
      routes: {'GET /version': () => ({version: 'stable', mode: process.env.REPORT_MODE, tableId: AnkoleRuntime.bindings.table('orders').tableId})},
      actions: {work: {concurrency: 'serial_fifo', idempotent: true, maxSlices: 25, handler: () => ({version: 'stable'})}}
    }
    """

    files = [
      {"server/main.js", source},
      {"applet.env.json", ~s({"REPORT_MODE":"default"})},
      {"applet.bindings.json", binding_manifest}
    ]

    for revision <- 0..2, do: assert({:ok, _} = publish(ctx, revision, "stable", files))

    assert {:ok, _} =
             Repo.transact_top_level(fn ->
               Ankole.Ash.destroy_where(
                 Ash.Query.filter(AppletRevision, page_id == ^ctx.page.id and revision == 3),
                 :remove
               )
             end)

    assert {:ok, _} =
             Ankole.Pod.Applets.Env.put(ctx.actor, ctx.page.id, "REPORT_MODE", %{
               value: "editor override",
               secret: false
             })

    request = %{"method" => "GET", "path" => "/version", "query" => %{}}

    assert {:ok, %{"body" => %{"tableId" => default_table_id}}} =
             Ankole.Pod.Applets.call(ctx.actor, ctx.page.id, request)

    assert default_table_id == first_table.id

    assert {:ok, bound} =
             Bindings.put(ctx.actor, ctx.page.id, "orders", %{table_id: chosen_table.id})

    assert {:ok, %{"body" => %{"tableId" => bound_table_id}}} =
             Ankole.Pod.Applets.call(ctx.actor, ctx.page.id, request)

    assert bound_table_id == chosen_table.id

    assert {:ok, job} =
             Ankole.AutomationJobs.create_applet_job(ctx.actor, ctx.page.id, "work", %{
               authorization_kind: "service"
             })

    {:ok, artifact} = Drive.store("generated report")

    assert {:ok, _} =
             Repo.transact_top_level(fn ->
               Files.commit_files_in_tx(ctx.page.id, [
                 %{path: "assets/report.txt", object: artifact, content_type: "text/plain"}
               ])
             end)

    next_source =
      source
      |> String.replace("stable", "candidate")
      |> String.replace("serial_fifo", "parallel")
      |> String.replace("idempotent: true", "idempotent: false")
      |> String.replace("maxSlices: 25", "maxSlices: 2")

    next_files = List.keyreplace(files, "server/main.js", 0, {"server/main.js", next_source})
    assert {:ok, %{draft: draft}} = publish(ctx, 3, "candidate", next_files, draft: true)

    assert {:ok, %{"body" => %{"version" => "stable"}}} =
             Ankole.Pod.Applets.call(ctx.actor, ctx.page.id, request)

    assert {:ok, %{concurrency_mode: :serial_fifo, idempotent: true, max_slices: 25}} =
             Ankole.AutomationJobs.get_automation_job(job.id)

    assert {:ok,
            %{
              "body" => %{
                "version" => "candidate",
                "mode" => "editor override",
                "tableId" => table_id
              }
            }} =
             Ankole.Pod.Applets.call(ctx.actor, ctx.page.id, request,
               revision: "draft:" <> draft.id
             )

    assert table_id == chosen_table.id
    assert {:ok, %{revision: 4}} = Revisions.promote(ctx.actor, ctx.page.id, draft.id, 3)

    assert {:ok, %{concurrency_mode: :parallel, idempotent: false, max_slices: 2}} =
             Ankole.AutomationJobs.get_automation_job(job.id)

    assert {:ok, %{"body" => %{"version" => "candidate"}}} =
             Ankole.Pod.Applets.call(ctx.actor, ctx.page.id, request)

    assert {:ok, %{revision: 5}} = Revisions.rollback(ctx.actor, ctx.page.id, 3, 4)

    assert {:ok, %{concurrency_mode: :serial_fifo, idempotent: true, max_slices: 25}} =
             Ankole.AutomationJobs.get_automation_job(job.id)

    assert {:ok,
            %{
              "body" => %{
                "version" => "stable",
                "mode" => "editor override",
                "tableId" => ^table_id
              }
            }} = Ankole.Pod.Applets.call(ctx.actor, ctx.page.id, request)

    assert {:ok, rebound} = Bindings.list(ctx.actor, ctx.page.id)
    assert rebound.bindings_digest == bound.bindings_digest
    assert {:ok, report} = Files.fetch_file(ctx.page.id, "assets/report.txt")
    assert {:ok, "generated report"} = Drive.read_object(report.object_id)
  end

