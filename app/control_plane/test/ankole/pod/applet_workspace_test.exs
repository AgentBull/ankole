  test "idempotency lease exceeds 240s Action ceiling and rejects stale claim_id completion or release",
       ctx do
    alias Ankole.Pod.AppletIdempotencyKey
    alias Ankole.Pod.Applets.{Capabilities, Idempotency}

    context = %{"applet" => %{"pageId" => ctx.page.id, "revision" => 0}}
    before_claim = DateTime.utc_now(:microsecond)

    assert {:ok, %{"status" => "claimed", "claim_id" => claim_id_1}} =
             Capabilities.call(context, ctx.actor, "idempotency.claim", ["lease-key", "hash-1"])

    assert is_binary(claim_id_1) and claim_id_1 != ""

    row_1 =
      AppletIdempotencyKey
      |> Ash.Query.filter(page_id == ^ctx.page.id and idempotency_key == "lease-key")
      |> Ankole.Ash.read_one!()

    # (a) Default SDK claim TTL exceeds the 240s Action ceiling
    assert DateTime.diff(row_1.expires_at, before_claim, :second) > 240
    assert row_1.response_body["claim_id"] == claim_id_1

    for args <- [
          ["lease-key", %{}],
          ["lease-key", %{}, 3600],
          ["lease-key", %{}, 3600, nil],
          ["lease-key", %{}, 3600, ""],
          [%{"key" => "lease-key", "value" => %{}}]
        ] do
      assert {:error, %{code: "invalid_request"}} =
               Capabilities.call(context, ctx.actor, "idempotency.complete", args)
    end

    for args <- [["lease-key"], ["lease-key", nil], ["lease-key", ""], [%{"key" => "lease-key"}]] do
      assert {:error, %{code: "invalid_request"}} =
               Capabilities.call(context, ctx.actor, "idempotency.release", args)
    end

    # Simulate expiry of claim 1 and acquisition of a fresh claim 2
    expired = DateTime.add(DateTime.utc_now(:microsecond), -5, :second)

    Repo.query!(
      "UPDATE pod_applet_idempotency_keys SET expires_at = $1 WHERE tenant_id = $2 AND page_id = $3 AND idempotency_key = $4",
      [expired, Ecto.UUID.dump!(Repo.tenant_id!()), Ecto.UUID.dump!(ctx.page.id), "lease-key"]
    )

    deadline_ctx = Map.put(context, "deadline", System.monotonic_time(:millisecond) + 900_000)

    assert {:ok, %{"status" => "claimed", "claim_id" => claim_id_2}} =
             Capabilities.call(
               deadline_ctx,
               ctx.actor,
               "idempotency.claim",
               ["lease-key", "hash-1"]
             )

    refute claim_id_1 == claim_id_2

    current_claim =
      Repo.get_by!(AppletIdempotencyKey, page_id: ctx.page.id, idempotency_key: "lease-key")

    assert DateTime.diff(current_claim.expires_at, DateTime.utc_now(), :second) >= 929

    assert {:ok, %{"status" => "claimed"}} =
             Idempotency.sdk_claim(ctx.page.id, ctx.uid, "long-timeout", "hash",
               timeout_ms: 600_000
             )

    timeout_claim = Repo.get_by!(AppletIdempotencyKey, idempotency_key: "long-timeout")
    assert DateTime.diff(timeout_claim.expires_at, DateTime.utc_now(), :second) >= 629

    # (b) Stale claim_id_1 cannot overwrite or release claim_id_2's in-flight row
    assert {:ok, %{"completed" => true}} =
             Capabilities.call(
               context,
               ctx.actor,
               "idempotency.complete",
               ["lease-key", %{"stale" => true}, 3600, claim_id_1]
             )

    assert {:ok, %{"released" => true}} =
             Capabilities.call(
               context,
               ctx.actor,
               "idempotency.release",
               ["lease-key", claim_id_1]
             )

    still_claimed =
      AppletIdempotencyKey
      |> Ash.Query.filter(page_id == ^ctx.page.id and idempotency_key == "lease-key")
      |> Ankole.Ash.read_one!()

    assert still_claimed.status_code == 0
    assert still_claimed.response_body["claim_id"] == claim_id_2

    # Active claim_id_2 completes cleanly and replays its value; subsequent stale release is a no-op
    assert {:ok, %{"completed" => true}} =
             Idempotency.sdk_complete(
               ctx.page.id,
               ctx.uid,
               "lease-key",
               %{"fresh" => 42},
               3600,
               claim_id_2
             )

    assert {:ok, %{"released" => true}} =
             Idempotency.sdk_release(ctx.page.id, ctx.uid, "lease-key", claim_id_1)

    assert {:ok, %{"status" => "replayed", "value" => %{"fresh" => 42}}} =
             Idempotency.sdk_claim(ctx.page.id, ctx.uid, "lease-key", "hash-1")
  end

