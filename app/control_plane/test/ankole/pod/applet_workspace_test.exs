  test "put binding rejects another member's private Base table without leaking field metadata",
       ctx do
    other = human_fixture().principal
    other_actor = actor_fixture(other)
    {:ok, private_base} = Pages.create(other_actor, %{type: "base", private_owner_uid: other.uid})

    {:ok, secret_table} =
      Bases.create_table(other_actor, private_base.id, %{name: "Compensation"})

    {:ok, _salary} =
      Bases.create_field(other_actor, secret_table.id, %{name: "salary", type: "number"})

    manifest = %{"tables" => %{"orders" => %{"fields" => %{"salary" => %{"type" => "number"}}}}}
    publish(ctx, 0, "one", [{"applet.bindings.json", Torque.encode!(manifest)}])

    assert {:error, :forbidden} =
             Bindings.put(ctx.actor, ctx.page.id, "orders", %{table_id: secret_table.id})

    # Publishing an applet.bindings.json referencing another user's live private Base is also rejected.
    forged_manifest = %{
      "tables" => %{
        "orders" => %{
          "tableId" => secret_table.id,
          "fields" => %{"salary" => %{"type" => "number"}}
        }
      }
    }

    assert {:error, :forbidden} =
             publish(ctx, 1, "forged", [{"applet.bindings.json", Torque.encode!(forged_manifest)}])

    # A trashed Base resolves as missing_table (tableId: nil) and allows template publication.
    {:ok, own_base} = Pages.create(ctx.actor, %{type: "base", private_owner_uid: ctx.uid})
    {:ok, own_table} = Bases.create_table(ctx.actor, own_base.id, %{name: "Orders"})
    {:ok, amount} = Bases.create_field(ctx.actor, own_table.id, %{name: "amount", type: "number"})

    own_manifest = %{
      "tables" => %{
        "orders" => %{
          "tableId" => own_table.id,
          "fields" => %{"amount" => %{"fieldId" => amount.id, "type" => "number"}}
        }
      }
    }

    assert {:ok, %{revision: 2}} =
             publish(ctx, 1, "bound", [{"applet.bindings.json", Torque.encode!(own_manifest)}])

    assert {:ok, %{bindings: %{"orders" => %{status: "ready", tableId: bound_id}}}} =
             Bindings.list(ctx.actor, ctx.page.id)

    assert bound_id == own_table.id

    assert {:ok, _} = Pages.delete(ctx.actor, own_base.id)

    assert {:ok, %{bindings: %{"orders" => %{status: "missing_table", tableId: nil}}}} =
             Bindings.list(ctx.actor, ctx.page.id)

    assert {:ok, %{revision: 3}} =
             publish(ctx, 2, "trashed-ok", [
               {"applet.bindings.json", Torque.encode!(own_manifest)}
             ])

    # Unauthorized callers probing a private non-applet receive :forbidden rather than :invalid_page_type.
    {:ok, private_doc} = Pages.create(other_actor, %{type: "doc", private_owner_uid: other.uid})
    assert {:error, :forbidden} = Bindings.list(ctx.actor, private_doc.id)
    assert {:error, :forbidden} = Bindings.put(ctx.actor, private_doc.id, "orders", %{})
    assert {:error, :forbidden} = Bindings.delete(ctx.actor, private_doc.id, "orders")
    assert {:error, :invalid_page_type} = Bindings.list(other_actor, private_doc.id)
  end

