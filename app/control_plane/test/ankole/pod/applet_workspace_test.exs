  defp publish(ctx, revision, html, extra \\ [], opts \\ []) do
    files =
      Enum.map(
        [{"src/main.tsx", "export default function App() {}"}, {"dist/index.html", html}] ++ extra,
        fn {path, bytes} ->
          {:ok, blob} = Drive.store(bytes)
          source_path = "applet-workspace/#{ctx.page.id}/#{path}"
          {:ok, _} = Drive.commit(ctx.uid, [Map.merge(blob, %{path: source_path, source: "pod"})])
          %{path: path, object_id: blob.object_id, source_path: source_path}
        end
      )

    Files.publish(ctx.actor, ctx.page.id, revision, files, nil, opts)
  end
