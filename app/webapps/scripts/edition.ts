export const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..')
export const edition = process.env.ANKOLE_EDITION ?? 'foss'
if (edition !== 'foss' && edition !== 'saas') throw new Error('ANKOLE_EDITION must be foss or saas')

export const internalsRoot = process.env.ANKOLE_INTERNALS_PATH?.trim()
  ? path.resolve(repositoryRoot, 'app/control_plane', process.env.ANKOLE_INTERNALS_PATH)
  : path.join(repositoryRoot, 'internals')
export const artifactRoot = path.join(repositoryRoot, 'app/control_plane/_build', edition)
export const localeDirectory = path.join(artifactRoot, 'locales')
export const assetsDirectory = path.join(artifactRoot, 'webapps/assets')
export const editionModulesFile = path.join(artifactRoot, 'webapps/edition-modules.gen.ts')

export interface EditionWebappModuleEntry {
  id: string
  file: string
}

export function webappEntries(): Record<string, string> {
  const entries = publicEntries()
  if (edition === 'saas') {
    const privateRoot = path.join(internalsRoot, 'webapps')
    const manifest = JSON.parse(readFileSync(path.join(privateRoot, 'entries.json'), 'utf8'))
    const privateEntries = readEntries(privateRoot, manifest.entries)
    const overrides = readEntries(privateRoot, manifest.overrides ?? {})
    for (const [name, file] of Object.entries(privateEntries)) {
      if (name in entries) throw new Error(`Duplicate webapp entry: ${name}`)
      entries[name] = file
    }
    for (const [name, file] of Object.entries(overrides)) {
      if (!(name in publicEntries())) throw new Error(`Unknown public webapp override: ${name}`)
      entries[name] = file
    }
  }
  return entries
}

/**
 * The SaaS manifest can replace a shared asset, such as a UIKit font, with its own file. Each `assets` key names the
 * shared file, and every import or CSS `url()` that ends in that file name resolves to the SaaS file instead.
 */
export function editionAssetAliases(): { find: RegExp; replacement: string }[] {
  if (edition !== 'saas') return []
  const privateRoot = path.join(internalsRoot, 'webapps')
  const manifest = JSON.parse(readFileSync(path.join(privateRoot, 'entries.json'), 'utf8'))
  return Object.entries(readEntries(privateRoot, manifest.assets ?? {}, /^[A-Za-z0-9][A-Za-z0-9._-]*$/)).map(
    ([name, file]) => ({
      find: new RegExp(`^(?:.*/)?${name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}$`),
      replacement: file
    })
  )
}

export function editionWebappModules(
  customInternalsRoot = internalsRoot,
  currentEdition = edition
): EditionWebappModuleEntry[] {
  if (currentEdition !== 'saas') return []
  const moduleIdPattern = /^[a-z][a-z0-9_-]*$/
  const discovered = new Map<string, string>()

  const registerModule = (id: string, file: string) => {
    if (!moduleIdPattern.test(id)) throw new Error(`Invalid webapp module ID: ${id}`)
    const existing = discovered.get(id)
    if (existing && existing !== file) throw new Error(`Duplicate webapp module: ${id}`)
    discovered.set(id, file)
  }

  const privateRoot = path.join(customInternalsRoot, 'webapps')
  const manifestPath = path.join(privateRoot, 'entries.json')
  if (existsSync(manifestPath)) {
    const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
    if (manifest.modules !== undefined) {
      for (const [id, file] of Object.entries(readEntries(privateRoot, manifest.modules, moduleIdPattern))) {
        registerModule(id, file)
      }
    }
  }

  const scanGroups = [
    { root: path.join(customInternalsRoot, 'webapps/modules'), subpath: '' },
    { root: path.join(customInternalsRoot, 'plugins'), subpath: 'webapps' }
  ]
  for (const { root, subpath } of scanGroups) {
    if (!existsSync(root)) continue
    for (const entry of readdirSync(root, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      if (!entry.isDirectory()) continue
      const id = entry.name
      const moduleDir = subpath ? path.join(root, id, subpath) : path.join(root, id)
      const candidates = ['extension.tsx', 'extension.ts']
        .map(name => path.join(moduleDir, name))
        .filter(candidate => existsSync(candidate))
      if (candidates.length > 1) throw new Error(`Multiple extension entrypoints in ${moduleDir}`)
      if (candidates[0]) registerModule(id, candidates[0])
    }
  }

  return [...discovered.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([id, file]) => ({ id, file }))
}

export function prepareEditionModules(targetFile = editionModulesFile, modules = editionWebappModules()): void {
  mkdirSync(path.dirname(targetFile), { recursive: true })
  const lines = ['// Generated by app/webapps/scripts/edition.ts. Do not edit.']
  if (modules.length === 0) {
    lines.push('export const editionModules = [] as const')
  } else {
    const slotsPath = path.join(repositoryRoot, 'app/webapps/common/slots')
    lines.push(`import type { EditionWebappModule } from ${JSON.stringify(slotsPath)}`)
    for (const [index, mod] of modules.entries()) {
      lines.push(`import module${index} from ${JSON.stringify(mod.file)}`)
    }
    lines.push('')
    for (const [index] of modules.entries()) {
      lines.push(`const entry${index}: EditionWebappModule = module${index}`)
    }
    lines.push('')
    lines.push('export const editionModules: readonly EditionWebappModule[] = [')
    for (const [index, mod] of modules.entries()) {
      lines.push(`  { ...entry${index}, id: entry${index}.id ?? ${JSON.stringify(mod.id)} },`)
    }
    lines.push(']')
  }
  const text = `${lines.join('\n')}\n`
  if (!existsSync(targetFile) || readFileSync(targetFile, 'utf8') !== text) {
    writeFileSync(targetFile, text)
  }
}

export function prepareEdition(): void {
  if (edition === 'saas') {
    const sharedDependencies = path.join(repositoryRoot, 'app/webapps/node_modules')
    ensureSharedDependenciesLink(path.join(internalsRoot, 'webapps/node_modules'), sharedDependencies)
    const pluginsRoot = path.join(internalsRoot, 'plugins')
    if (existsSync(pluginsRoot)) {
      for (const entry of readdirSync(pluginsRoot, { withFileTypes: true })) {
        if (!entry.isDirectory()) continue
        const pluginWebapps = path.join(pluginsRoot, entry.name, 'webapps')
        if (existsSync(pluginWebapps)) {
          ensureSharedDependenciesLink(path.join(pluginWebapps, 'node_modules'), sharedDependencies)
        }
      }
    }
  }
  webappEntries()
  prepareEditionModules()
  prepareLocales()
}

function ensureSharedDependenciesLink(privateDependencies: string, sharedDependencies: string): void {
  const target = path.relative(path.dirname(privateDependencies), sharedDependencies)
  const current = lstatSync(privateDependencies, { throwIfNoEntry: false })
  if (!current || (current.isSymbolicLink() && readlinkSync(privateDependencies) !== target)) {
    const temporary = `${privateDependencies}.${crypto.randomUUID()}`
    try {
      symlinkSync(target, temporary, 'dir')
      renameSync(temporary, privateDependencies)
    } finally {
      rmSync(temporary, { force: true })
    }
  }
  if (realpathSync(privateDependencies) !== realpathSync(sharedDependencies)) {
    throw new Error('SaaS webapps must use app/webapps/node_modules')
  }
}

function publicEntries(): Record<string, string> {
  const root = path.join(repositoryRoot, 'app/webapps')
  return readEntries(root, JSON.parse(readFileSync(path.join(root, 'entries.json'), 'utf8')))
}

function readEntries(root: string, entries: unknown, names = /^[a-z][a-z0-9-]*$/): Record<string, string> {
  if (!entries || typeof entries !== 'object' || Array.isArray(entries)) throw new Error('Invalid webapp entries')
  return Object.fromEntries(
    Object.entries(entries).map(([name, relative]) => {
      if (!names.test(name) || typeof relative !== 'string') throw new Error('Invalid webapp entry')
      const file = path.resolve(root, relative)
      if (!file.startsWith(root + path.sep) || !existsSync(file)) throw new Error(`Missing webapp entry: ${file}`)
      return [name, file]
    })
  )
}

/** Both Phoenix and Vite read these generated catalogs; source files stay unchanged. */
export function prepareLocales(): void {
  const catalogs = new Map<string, Record<string, unknown>>()
  const roots = [path.join(repositoryRoot, 'app/locales')]
  if (edition === 'saas') {
    roots.push(path.join(internalsRoot, 'locales'))
    for (const parent of [path.join(internalsRoot, 'webapps/modules'), path.join(internalsRoot, 'plugins')]) {
      if (!existsSync(parent)) continue
      for (const entry of readdirSync(parent, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
        if (!entry.isDirectory()) continue
        const moduleLocales = path.join(parent, entry.name, 'locales')
        if (existsSync(moduleLocales)) roots.push(moduleLocales)
      }
    }
  }
  for (const root of roots) {
    for (const file of readdirSync(root)
      .filter(file => file.endsWith('.toml'))
      .sort()) {
      const locale = path.basename(file, '.toml')
      const source = Bun.TOML.parse(readFileSync(path.join(root, file), 'utf8'))
      if (!table(source)) throw new Error(`Invalid locale catalog: ${file}`)
      const target = catalogs.get(locale) ?? {}
      mergeCatalog(target, source, `${locale}:`)
      catalogs.set(locale, target)
    }
  }
  mkdirSync(localeDirectory, { recursive: true })
  const expected = new Set([...catalogs.keys()].map(locale => `${locale}.json`))
  for (const file of readdirSync(localeDirectory)) {
    if (!expected.has(file)) rmSync(path.join(localeDirectory, file))
  }
  for (const [locale, catalog] of catalogs) {
    const file = path.join(localeDirectory, `${locale}.json`)
    const text = `${JSON.stringify(catalog)}\n`
    if (!existsSync(file) || readFileSync(file, 'utf8') !== text) writeFileSync(file, text)
  }
}

function mergeCatalog(target: Record<string, unknown>, source: Record<string, unknown>, prefix: string): void {
  for (const [key, value] of Object.entries(source)) {
    if (!(key in target)) target[key] = value
    else if (table(target[key]) && table(value) && target[key].__mf2__ !== true && value.__mf2__ !== true) {
      mergeCatalog(target[key], value, `${prefix}${key}.`)
    } else throw new Error(`Duplicate locale key: ${prefix}${key}`)
  }
}

function table(value: unknown): value is Record<string, unknown> {
  return value !== null && typeof value === 'object' && !Array.isArray(value)
}
